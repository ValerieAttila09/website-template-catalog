import "@supabase/functions-js/edge-runtime.d.ts";

export default {
  async fetch(req: Request): Promise<Response> {
    const { name } = await req.json() as { name?: string };

    return Response.json({
      message: `Hello ${name ?? "there"}!`,
    });
  },
};

